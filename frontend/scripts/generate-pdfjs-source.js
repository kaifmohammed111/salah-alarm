#!/usr/bin/env node
// Run this again (no npm install needed — pdfjs-dist is already installed):
//   node scripts/generate-pdfjs-source.js
//
// Reads BOTH the pdf.js main library build and its worker build, writing
// both out as plain TS string constants (src/lib/pdfjsSource.generated.ts).
// pdf.js needs the worker script even when not using disableWorker mode —
// this version loads it via a Blob URL inside the WebView (see
// pdfExtractHtml.ts), so it's still genuinely offline: no network fetch,
// no CDN, just embedded code turned into an in-memory blob at runtime.
const fs = require("fs");
const path = require("path");

function findFirst(candidates) {
  for (const c of candidates) {
    const full = path.join(__dirname, "..", c);
    if (fs.existsSync(full)) return full;
  }
  return null;
}

const libPath = findFirst([
  "node_modules/pdfjs-dist/build/pdf.min.js",
  "node_modules/pdfjs-dist/build/pdf.js",
  "node_modules/pdfjs-dist/legacy/build/pdf.min.js",
  "node_modules/pdfjs-dist/legacy/build/pdf.js",
]);

const workerPath = findFirst([
  "node_modules/pdfjs-dist/build/pdf.worker.min.js",
  "node_modules/pdfjs-dist/build/pdf.worker.js",
  "node_modules/pdfjs-dist/legacy/build/pdf.worker.min.js",
  "node_modules/pdfjs-dist/legacy/build/pdf.worker.js",
]);

if (!libPath || !workerPath) {
  console.error("Could not find pdfjs-dist build files. Did you run:");
  console.error("  npm install pdfjs-dist@2.16.105");
  console.error("first? (run from the frontend/ directory)");
  if (!libPath) console.error("  missing: pdf.min.js / pdf.js");
  if (!workerPath) console.error("  missing: pdf.worker.min.js / pdf.worker.js");
  process.exit(1);
}

const libSource = fs.readFileSync(libPath, "utf8");
const workerSource = fs.readFileSync(workerPath, "utf8");
const outPath = path.join(__dirname, "..", "src", "lib", "pdfjsSource.generated.ts");

const banner =
  "// AUTO-GENERATED by scripts/generate-pdfjs-source.js — do not hand-edit.\n" +
  "// Regenerate with: node scripts/generate-pdfjs-source.js\n" +
  `// Lib source: ${path.relative(path.join(__dirname, ".."), libPath)}\n` +
  `// Worker source: ${path.relative(path.join(__dirname, ".."), workerPath)}\n\n`;

const content =
  banner +
  "export const PDFJS_LIB_SOURCE = " + JSON.stringify(libSource) + ";\n\n" +
  "export const PDFJS_WORKER_SOURCE = " + JSON.stringify(workerSource) + ";\n";

fs.writeFileSync(outPath, content, "utf8");
console.log(`Wrote ${content.length.toLocaleString()} chars to src/lib/pdfjsSource.generated.ts`);
console.log(`  lib:    ${libSource.length.toLocaleString()} chars (${path.relative(path.join(__dirname, ".."), libPath)})`);
console.log(`  worker: ${workerSource.length.toLocaleString()} chars (${path.relative(path.join(__dirname, ".."), workerPath)})`);
